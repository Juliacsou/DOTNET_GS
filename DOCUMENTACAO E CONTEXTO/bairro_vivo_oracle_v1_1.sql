-- IDs NUMBER(19) sao gerados pelo Oracle. O claim sub do JWT Java contera
-- a representacao STRING desse ID (por exemplo, "1").
CREATE TABLE TB_USUARIO (
    ID_USUARIO        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME              VARCHAR2(120) NOT NULL,
    EMAIL             VARCHAR2(180) NOT NULL,
    SENHA_HASH        VARCHAR2(255) NOT NULL,
    PAPEL             VARCHAR2(12) DEFAULT 'CIDADAO' NOT NULL,
    FL_ATIVO          CHAR(1) DEFAULT 'S' NOT NULL,
    DT_CRIACAO        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    DT_ATUALIZACAO    TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT CK_USUARIO_PAPEL CHECK (PAPEL IN ('CIDADAO','ADMIN')),
    CONSTRAINT CK_USUARIO_ATIVO CHECK (FL_ATIVO IN ('S','N'))
);
CREATE UNIQUE INDEX UX_USUARIO_EMAIL ON TB_USUARIO (LOWER(EMAIL));

