-- Cada foto pertence a uma ocorrencia; opcionalmente referencia uma atualizacao.
-- A FK composta verifica o vinculo quando ID_ATUALIZACAO nao for NULL;
-- para fotos de ocorrencia (sem atualizacao), o .NET verifica a autoria.
CREATE TABLE TB_MIDIA (
    ID_MIDIA          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_OCORRENCIA     NUMBER(19) NOT NULL,
    ID_ATUALIZACAO    NUMBER(19),
    ID_USUARIO        NUMBER(19) NOT NULL,
    PROVEDOR          VARCHAR2(40) NOT NULL,
    CHAVE_STORAGE     VARCHAR2(500) NOT NULL,
    URL_EXIBICAO      VARCHAR2(1000),
    MIME_TYPE         VARCHAR2(60) NOT NULL,
    TAMANHO_BYTES     NUMBER(12) NOT NULL,
    DT_CRIACAO        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MIDIA PRIMARY KEY (ID_MIDIA),
    CONSTRAINT FK_MIDIA_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES TB_OCORRENCIA (ID_OCORRENCIA),
    CONSTRAINT FK_MIDIA_ATUALIZACAO FOREIGN KEY (ID_ATUALIZACAO, ID_OCORRENCIA, ID_USUARIO)
       REFERENCES TB_ATUALIZACAO (ID_ATUALIZACAO, ID_OCORRENCIA, ID_USUARIO),
    CONSTRAINT FK_MIDIA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO),
    CONSTRAINT UX_MIDIA_CHAVE UNIQUE (PROVEDOR, CHAVE_STORAGE),
    CONSTRAINT CK_MIDIA_TIPO CHECK (MIME_TYPE IN ('image/jpeg','image/png','image/webp')),
    CONSTRAINT CK_MIDIA_TAMANHO CHECK (TAMANHO_BYTES > 0)
