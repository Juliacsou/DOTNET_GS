-- PACKAGE 1: Regras de participacao comunitaria.
CREATE OR REPLACE PACKAGE PKG_COMUNIDADE AS
    FUNCTION FN_TOTAL_VOTOS_ATIVOS (
        P_ID_OCORRENCIA IN NUMBER,
        P_TIPO_VOTO     IN VARCHAR2
    ) RETURN NUMBER;

    -- Usada exclusivamente pela trigger para impedir alteracao direta de status.
    FUNCTION FN_TRANSICAO_AUTORIZADA RETURN CHAR;

    PROCEDURE PR_REGISTRAR_ATUALIZACAO (
        P_ID_OCORRENCIA  IN NUMBER,
        P_ID_USUARIO     IN NUMBER,
        P_TIPO           IN VARCHAR2,
        P_TEXTO          IN CLOB,
        P_FL_ANONIMO     IN CHAR,
        P_ID_ATUALIZACAO OUT NUMBER
    );
END PKG_COMUNIDADE;
/

CREATE OR REPLACE PACKAGE BODY PKG_COMUNIDADE AS
    -- Variavel privada, isolada por sessao Oracle, sem setter publico.
    G_PERMITIR_TRANSICAO BOOLEAN := FALSE;

    FUNCTION FN_TRANSICAO_AUTORIZADA RETURN CHAR IS
    BEGIN
        IF G_PERMITIR_TRANSICAO THEN RETURN 'S'; END IF;
        RETURN 'N';
    END FN_TRANSICAO_AUTORIZADA;

    FUNCTION FN_TOTAL_VOTOS_ATIVOS (
        P_ID_OCORRENCIA IN NUMBER,
        P_TIPO_VOTO     IN VARCHAR2
    ) RETURN NUMBER IS
        V_CICLO NUMBER;
        V_TOTAL NUMBER;
    BEGIN
        IF P_TIPO_VOTO NOT IN ('PERSISTE','RESOLVIDO') OR P_TIPO_VOTO IS NULL THEN
            RAISE_APPLICATION_ERROR(-20040,'Tipo de voto invalido.');
        END IF;
        SELECT NUM_CICLO INTO V_CICLO
          FROM TB_OCORRENCIA WHERE ID_OCORRENCIA = P_ID_OCORRENCIA;
        SELECT COUNT(*) INTO V_TOTAL
          FROM TB_VOTO_SITUACAO
         WHERE ID_OCORRENCIA = P_ID_OCORRENCIA
           AND NUM_CICLO = V_CICLO
           AND TIPO_VOTO = P_TIPO_VOTO;
        RETURN V_TOTAL;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20041,'Ocorrencia nao encontrada.');
    END FN_TOTAL_VOTOS_ATIVOS;

    PROCEDURE PR_REGISTRAR_ATUALIZACAO (
        P_ID_OCORRENCIA  IN NUMBER,
        P_ID_USUARIO     IN NUMBER,
        P_TIPO           IN VARCHAR2,
        P_TEXTO          IN CLOB,
        P_FL_ANONIMO     IN CHAR,
        P_ID_ATUALIZACAO OUT NUMBER
    ) IS
        V_STATUS    TB_OCORRENCIA.STATUS%TYPE;
        V_CICLO     TB_OCORRENCIA.NUM_CICLO%TYPE;
        V_TOTAL     NUMBER;
        V_USUARIO   NUMBER;
        V_VOTO      CHAR(1) := 'N';
        V_NOVO_STATUS TB_OCORRENCIA.STATUS%TYPE;
    BEGIN
        G_PERMITIR_TRANSICAO := FALSE;
        IF P_TIPO IS NULL OR P_TIPO NOT IN ('COMENTARIO','PERSISTE','RESOLVIDO') THEN
            RAISE_APPLICATION_ERROR(-20050,'Tipo de atualizacao invalido.');
        END IF;
        IF P_FL_ANONIMO IS NULL OR P_FL_ANONIMO NOT IN ('S','N') THEN
            RAISE_APPLICATION_ERROR(-20051,'Flag de anonimato invalida.');
        END IF;

        SELECT COUNT(*) INTO V_USUARIO FROM TB_USUARIO
         WHERE ID_USUARIO = P_ID_USUARIO AND PAPEL = 'CIDADAO' AND FL_ATIVO = 'S';
        IF V_USUARIO <> 1 THEN
            RAISE_APPLICATION_ERROR(-20052,'Somente cidadao ativo pode atualizar.');
        END IF;

        -- Lock na ocorrencia serializa votos concorrentes e impede contagem dupla.
        SELECT STATUS, NUM_CICLO INTO V_STATUS, V_CICLO
          FROM TB_OCORRENCIA
         WHERE ID_OCORRENCIA = P_ID_OCORRENCIA AND FL_EXCLUIDA = 'N'
         FOR UPDATE;

        IF (V_STATUS = 'ABERTA' AND P_TIPO = 'RESOLVIDO') OR
           (V_STATUS = 'RESOLVIDA' AND P_TIPO = 'PERSISTE') THEN
            V_VOTO := 'S';
        END IF;

        IF V_VOTO = 'S' THEN
            SELECT COUNT(*) INTO V_TOTAL FROM TB_VOTO_SITUACAO
             WHERE ID_OCORRENCIA = P_ID_OCORRENCIA
               AND ID_USUARIO = P_ID_USUARIO
               AND NUM_CICLO = V_CICLO;
            IF V_TOTAL > 0 THEN
                RAISE_APPLICATION_ERROR(-20053,'Usuario ja votou no ciclo atual.');
            END IF;
        END IF;

        INSERT INTO TB_ATUALIZACAO (
            ID_OCORRENCIA, ID_USUARIO, TIPO, TEXTO, FL_ANONIMO
        ) VALUES (
            P_ID_OCORRENCIA, P_ID_USUARIO, P_TIPO, P_TEXTO, P_FL_ANONIMO
        ) RETURNING ID_ATUALIZACAO INTO P_ID_ATUALIZACAO;

        IF V_VOTO = 'S' THEN
            INSERT INTO TB_VOTO_SITUACAO (
                ID_OCORRENCIA, ID_ATUALIZACAO, ID_USUARIO, NUM_CICLO, TIPO_VOTO
            ) VALUES (
                P_ID_OCORRENCIA, P_ID_ATUALIZACAO, P_ID_USUARIO, V_CICLO, P_TIPO
            );

            SELECT COUNT(*) INTO V_TOTAL FROM TB_VOTO_SITUACAO
             WHERE ID_OCORRENCIA = P_ID_OCORRENCIA
               AND NUM_CICLO = V_CICLO
               AND TIPO_VOTO = P_TIPO;

            IF V_TOTAL >= 2 THEN
                IF V_STATUS = 'ABERTA' THEN
                    V_NOVO_STATUS := 'RESOLVIDA';
                ELSE
                    V_NOVO_STATUS := 'ABERTA';
                END IF;

                G_PERMITIR_TRANSICAO := TRUE;
                BEGIN
                    UPDATE TB_OCORRENCIA
                       SET STATUS = V_NOVO_STATUS,
                           NUM_CICLO = NUM_CICLO + 1,
                           ID_AUTOR_TRANSICAO = P_ID_USUARIO
                     WHERE ID_OCORRENCIA = P_ID_OCORRENCIA;
                EXCEPTION WHEN OTHERS THEN
                    G_PERMITIR_TRANSICAO := FALSE;
                    RAISE;
                END;
                G_PERMITIR_TRANSICAO := FALSE;
            END IF;
        END IF;
        -- Sem COMMIT: a API decide quando confirmar ou desfazer a transacao.
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            G_PERMITIR_TRANSICAO := FALSE;
            RAISE_APPLICATION_ERROR(-20054,'Ocorrencia nao encontrada ou excluida.');
        WHEN OTHERS THEN
            G_PERMITIR_TRANSICAO := FALSE;
            RAISE;
    END PR_REGISTRAR_ATUALIZACAO;
END PKG_COMUNIDADE;
/

