CREATE OR REPLACE VIEW VW_TRECHOS_RAG_APROVADOS AS
SELECT T.ID_TRECHO, F.ID_FONTE, F.TITULO AS TITULO_FONTE, F.URL_FONTE,
       F.DT_VERIFICACAO, T.TEXTO_TRECHO,
       S.ID_SERVICO, O.ID_MUNICIPIO, SC.ID_CATEGORIA
  FROM TB_TRECHO_FONTE T
  JOIN TB_FONTE_OFICIAL F ON F.ID_FONTE = T.ID_FONTE
  JOIN TB_SERVICO_PUBLICO S ON S.ID_SERVICO = F.ID_SERVICO
  JOIN TB_ORGAO_PUBLICO O ON O.ID_ORGAO = S.ID_ORGAO
  JOIN TB_SERVICO_CATEGORIA SC ON SC.ID_SERVICO = S.ID_SERVICO
 WHERE T.FL_APROVADO = 'S' AND F.FL_VERIFICADA = 'S'
   AND O.FL_ATIVO = 'S' AND S.FL_ATIVO = 'S';

