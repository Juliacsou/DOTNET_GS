-- BLOCO PL/SQL #1 - cursor implicito FOR, repeticao e decisao.
-- Confere o minimo de 5 linhas em TODAS as 19 tabelas e objetos compilados.
DECLARE
    V_QTD   NUMBER;
    V_TABS  NUMBER := 0;
    V_INV   NUMBER;
BEGIN
    FOR T IN (
        SELECT TABLE_NAME FROM USER_TABLES
         WHERE TABLE_NAME IN (
           'TB_USUARIO','TB_PREFERENCIA_USUARIO','TB_LOCAL_FAVORITO',
           'TB_MUNICIPIO','TB_CATEGORIA','TB_OCORRENCIA',
           'TB_ATUALIZACAO','TB_MIDIA','TB_VOTO_SITUACAO',
           'TB_HISTORICO_STATUS','TB_ORGAO_PUBLICO','TB_SERVICO_PUBLICO',
           'TB_SERVICO_CATEGORIA','TB_CANAL_ATENDIMENTO','TB_FONTE_OFICIAL',
           'TB_ORIENTACAO_IA','TB_ORIENTACAO_FONTE','TB_TRECHO_FONTE',
           'TB_REQUISICAO_IDEMPOTENTE'
         ) ORDER BY TABLE_NAME
    ) LOOP
        EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ' || T.TABLE_NAME INTO V_QTD;
        DBMS_OUTPUT.PUT_LINE('CONTAGEM: ' || RPAD(T.TABLE_NAME,30) || ' = ' || V_QTD);
        IF V_QTD < 5 THEN
            RAISE_APPLICATION_ERROR(-20910,'Tabela com menos de 5 linhas: ' || T.TABLE_NAME);
        END IF;
        V_TABS := V_TABS + 1;
    END LOOP;
    IF V_TABS <> 19 THEN
        RAISE_APPLICATION_ERROR(-20911,'Esperadas 19 tabelas; encontradas: ' || V_TABS);
    END IF;

    SELECT COUNT(*) INTO V_INV FROM USER_OBJECTS
     WHERE OBJECT_NAME IN (
         'PKG_COMUNIDADE','PKG_BASE_IA',
         'TRG_OCORRENCIA_BIU','TRG_OCORRENCIA_AI','TRG_AUDITORIA_STATUS',
         'TRG_ORIENTACAO_FONTE_BIU',
