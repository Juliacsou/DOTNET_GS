DECLARE
    TYPE t_nomes IS TABLE OF VARCHAR2(60);
    v_packages t_nomes := t_nomes('PKG_COMUNIDADE','PKG_BASE_IA','PKG_SERVICOS_PUBLICOS');
    v_views t_nomes := t_nomes('VW_RELATORIO_OCORRENCIAS','VW_ORIENTACOES_PUBLICAS',
                             'VW_ATUALIZACOES_PUBLICAS','VW_OCORRENCIAS_PUBLICAS',
                             'VW_TRECHOS_RAG_APROVADOS');
    -- Ordem inversa das dependencias; CASCADE CONSTRAINTS como seguranca.
    v_tabelas t_nomes := t_nomes(
      'TB_REQUISICAO_IDEMPOTENTE', 'TB_ORIENTACAO_FONTE',
      'TB_ORIENTACAO_IA', 'TB_TRECHO_FONTE', 'TB_FONTE_OFICIAL', 'TB_CANAL_ATENDIMENTO',
      'TB_SERVICO_CATEGORIA', 'TB_SERVICO_PUBLICO', 'TB_ORGAO_PUBLICO',
      'TB_HISTORICO_STATUS', 'TB_VOTO_SITUACAO', 'TB_MIDIA',
      'TB_ATUALIZACAO', 'TB_OCORRENCIA', 'TB_CATEGORIA',
      'TB_MUNICIPIO', 'TB_LOCAL_FAVORITO',
      'TB_PREFERENCIA_USUARIO', 'TB_USUARIO'
    );
BEGIN
    FOR i IN 1 .. v_views.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP VIEW ' || v_views(i);
            DBMS_OUTPUT.PUT_LINE('DROP VIEW: ' || v_views(i));
        EXCEPTION WHEN OTHERS THEN
            IF SQLCODE <> -942 THEN RAISE; END IF;
        END;
    END LOOP;
    FOR i IN 1 .. v_packages.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP PACKAGE ' || v_packages(i);
            DBMS_OUTPUT.PUT_LINE('DROP PACKAGE: ' || v_packages(i));
        EXCEPTION WHEN OTHERS THEN
            IF SQLCODE <> -4043 THEN RAISE; END IF;
        END;
    END LOOP;
    FOR i IN 1 .. v_tabelas.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || v_tabelas(i) || ' CASCADE CONSTRAINTS PURGE';
            DBMS_OUTPUT.PUT_LINE('DROP TABLE: ' || v_tabelas(i));
        EXCEPTION WHEN OTHERS THEN
            IF SQLCODE <> -942 THEN RAISE; END IF;
        END;
    END LOOP;
END;
