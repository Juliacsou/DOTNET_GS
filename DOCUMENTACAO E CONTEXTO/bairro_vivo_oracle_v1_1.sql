       CASE WHEN A.FL_ANONIMO = 'S' THEN 'Cidadao anonimo'
            ELSE U.NOME END AS AUTOR_EXIBICAO
FROM TB_ATUALIZACAO A
JOIN TB_USUARIO U ON U.ID_USUARIO = A.ID_USUARIO
JOIN TB_OCORRENCIA O ON O.ID_OCORRENCIA = A.ID_OCORRENCIA
WHERE O.FL_EXCLUIDA = 'N';

-- API Java usa esta view para recuperar apenas conhecimento revisado.
