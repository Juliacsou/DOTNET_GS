CREATE OR REPLACE PACKAGE PKG_BASE_IA AS
    FUNCTION FN_TOTAL_SERVICOS_MUNICIPIO (
        P_ID_MUNICIPIO IN NUMBER
    ) RETURN NUMBER;

    FUNCTION FN_TOTAL_FONTES_APROVADAS (
        P_ID_SERVICO IN NUMBER
    ) RETURN NUMBER;

    PROCEDURE PR_REGISTRAR_ORIENTACAO (
        P_ID_OCORRENCIA    IN NUMBER,
        P_ID_USUARIO       IN NUMBER,
        P_ID_SERVICO       IN NUMBER,
        P_TEXTO_ORIENTACAO IN CLOB,
        P_MODELO_LLM       IN VARCHAR2,
        P_ESTADO           IN VARCHAR2,
        P_ID_FONTE         IN NUMBER,
        P_FL_PUBLICA       IN CHAR,
        P_ID_ORIENTACAO    OUT NUMBER
    );
END PKG_BASE_IA;
/

CREATE OR REPLACE PACKAGE BODY PKG_BASE_IA AS
    FUNCTION FN_TOTAL_SERVICOS_MUNICIPIO (
        P_ID_MUNICIPIO IN NUMBER
    ) RETURN NUMBER IS
        V_TOTAL NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_TOTAL
          FROM TB_SERVICO_PUBLICO S
          JOIN TB_ORGAO_PUBLICO O ON O.ID_ORGAO = S.ID_ORGAO
         WHERE O.ID_MUNICIPIO = P_ID_MUNICIPIO
           AND S.FL_ATIVO = 'S' AND O.FL_ATIVO = 'S';
        RETURN V_TOTAL;
    END FN_TOTAL_SERVICOS_MUNICIPIO;

    FUNCTION FN_TOTAL_FONTES_APROVADAS (
        P_ID_SERVICO IN NUMBER
    ) RETURN NUMBER IS
        V_TOTAL NUMBER;
    BEGIN
        SELECT COUNT(DISTINCT F.ID_FONTE) INTO V_TOTAL
          FROM TB_FONTE_OFICIAL F
          JOIN TB_TRECHO_FONTE T ON T.ID_FONTE = F.ID_FONTE
         WHERE F.ID_SERVICO = P_ID_SERVICO
           AND F.FL_VERIFICADA = 'S' AND T.FL_APROVADO = 'S';
        RETURN V_TOTAL;
    END FN_TOTAL_FONTES_APROVADAS;

    PROCEDURE PR_REGISTRAR_ORIENTACAO (
        P_ID_OCORRENCIA    IN NUMBER,
        P_ID_USUARIO       IN NUMBER,
        P_ID_SERVICO       IN NUMBER,
        P_TEXTO_ORIENTACAO IN CLOB,
        P_MODELO_LLM       IN VARCHAR2,
        P_ESTADO           IN VARCHAR2,
        P_ID_FONTE         IN NUMBER,
        P_FL_PUBLICA       IN CHAR,
        P_ID_ORIENTACAO    OUT NUMBER
    ) IS
        V_TOTAL NUMBER;
    BEGIN
        P_ID_ORIENTACAO := NULL;
        IF P_FL_PUBLICA IS NULL OR P_FL_PUBLICA NOT IN ('S','N') THEN
            RAISE_APPLICATION_ERROR(-20100,'Flag de publicacao invalida.');
        END IF;
        IF P_ESTADO IS NULL OR P_ESTADO NOT IN
             ('DISPONIVEL','PARCIAL','SEM_FONTE','LOCALIDADE_NAO_CONFIRMADA','ERRO') THEN
            RAISE_APPLICATION_ERROR(-20105,'Estado de orientacao invalido.');
        END IF;
        IF P_TEXTO_ORIENTACAO IS NULL OR DBMS_LOB.GETLENGTH(P_TEXTO_ORIENTACAO) = 0 THEN
            RAISE_APPLICATION_ERROR(-20101,'Texto de orientacao nao pode ser vazio.');
        END IF;
        SELECT COUNT(*) INTO V_TOTAL FROM TB_USUARIO
         WHERE ID_USUARIO = P_ID_USUARIO AND PAPEL = 'CIDADAO' AND FL_ATIVO = 'S';
        IF V_TOTAL <> 1 THEN
            RAISE_APPLICATION_ERROR(-20102,'Solicitante precisa ser cidadao ativo.');
        END IF;
        SELECT COUNT(*) INTO V_TOTAL FROM TB_OCORRENCIA
         WHERE ID_OCORRENCIA = P_ID_OCORRENCIA AND FL_EXCLUIDA = 'N';
        IF V_TOTAL <> 1 THEN
            RAISE_APPLICATION_ERROR(-20106,'Ocorrencia inexistente ou excluida.');
        END IF;

        IF P_ID_SERVICO IS NOT NULL THEN
            SELECT COUNT(*) INTO V_TOTAL
              FROM TB_OCORRENCIA C
              JOIN TB_SERVICO_CATEGORIA SC ON SC.ID_CATEGORIA = C.ID_CATEGORIA
              JOIN TB_SERVICO_PUBLICO S ON S.ID_SERVICO = SC.ID_SERVICO
              JOIN TB_ORGAO_PUBLICO O ON O.ID_ORGAO = S.ID_ORGAO
             WHERE C.ID_OCORRENCIA = P_ID_OCORRENCIA
               AND S.ID_SERVICO = P_ID_SERVICO
               AND O.ID_MUNICIPIO = C.ID_MUNICIPIO
               AND S.FL_ATIVO = 'S' AND O.FL_ATIVO = 'S';
            IF V_TOTAL <> 1 THEN
                RAISE_APPLICATION_ERROR(-20103,
                    'Servico incompativel com municipio/categoria da ocorrencia.');
            END IF;
        END IF;

        -- Respostas DISPONIVEL/PARCIAL so recebem citacao quando realmente ha
        -- fonte revisada E trecho aprovado correspondente ao servico.
        IF P_ESTADO IN ('DISPONIVEL','PARCIAL') THEN
            IF P_ID_SERVICO IS NULL OR P_ID_FONTE IS NULL THEN
                RAISE_APPLICATION_ERROR(-20104,
                    'Resposta fundamentada exige servico e fonte oficial verificada.');
            END IF;
            SELECT COUNT(*) INTO V_TOTAL
              FROM TB_FONTE_OFICIAL F
             WHERE F.ID_FONTE = P_ID_FONTE
               AND F.ID_SERVICO = P_ID_SERVICO
               AND F.FL_VERIFICADA = 'S'
               AND EXISTS (
                    SELECT 1 FROM TB_TRECHO_FONTE T
                    WHERE T.ID_FONTE = F.ID_FONTE AND T.FL_APROVADO = 'S'
               );
            IF V_TOTAL <> 1 THEN
                RAISE_APPLICATION_ERROR(-20104,
                    'Fonte oficial ausente, nao aprovada ou de outro servico.');
            END IF;
        ELSIF P_ID_FONTE IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20107,
                'Estado sem fundamentacao nao deve incluir ID_FONTE.');
        END IF;

        INSERT INTO TB_ORIENTACAO_IA (
            ID_OCORRENCIA, ID_USUARIO, ID_SERVICO, TEXTO_ORIENTACAO,
            MODELO_LLM, ESTADO_ORIENTACAO, FL_PUBLICA
        ) VALUES (
            P_ID_OCORRENCIA, P_ID_USUARIO, P_ID_SERVICO, P_TEXTO_ORIENTACAO,
            P_MODELO_LLM, P_ESTADO, P_FL_PUBLICA
        ) RETURNING ID_ORIENTACAO INTO P_ID_ORIENTACAO;
        IF P_ID_FONTE IS NOT NULL THEN
            INSERT INTO TB_ORIENTACAO_FONTE (ID_ORIENTACAO, ID_FONTE)
            VALUES (P_ID_ORIENTACAO, P_ID_FONTE);
        END IF;
        -- Sem COMMIT: transacao controlada pela API Java.
        -- Contatos/horarios devem ser montados SOMENTE de dados verificados.
    END PR_REGISTRAR_ORIENTACAO;
END PKG_BASE_IA;
