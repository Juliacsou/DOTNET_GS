-- TRIGGER 1: validacao de criacao, data de alteracao e bloqueio de status manual.
-- Nem ADMIN nem API devem executar UPDATE de STATUS: apenas PKG_COMUNIDADE.
CREATE OR REPLACE TRIGGER TRG_OCORRENCIA_BIU
BEFORE INSERT OR UPDATE ON TB_OCORRENCIA
FOR EACH ROW
BEGIN
    :NEW.DT_ATUALIZACAO := SYSTIMESTAMP;
    IF INSERTING THEN
        IF :NEW.STATUS <> 'ABERTA' OR :NEW.NUM_CICLO <> 1 THEN
            RAISE_APPLICATION_ERROR(-20202,'Nova ocorrencia deve iniciar ABERTA no ciclo 1.');
        END IF;
    ELSIF UPDATING THEN
        IF :OLD.STATUS <> :NEW.STATUS OR :OLD.NUM_CICLO <> :NEW.NUM_CICLO THEN
            IF PKG_COMUNIDADE.FN_TRANSICAO_AUTORIZADA <> 'S' THEN
                RAISE_APPLICATION_ERROR(-20200,'Status/ciclo somente por voto comunitario.');
            END IF;
            IF :NEW.STATUS = :OLD.STATUS OR :NEW.NUM_CICLO <> :OLD.NUM_CICLO + 1 THEN
                RAISE_APPLICATION_ERROR(-20201,'Transicao de status/ciclo inconsistente.');
            END IF;
        END IF;
    END IF;
END;
