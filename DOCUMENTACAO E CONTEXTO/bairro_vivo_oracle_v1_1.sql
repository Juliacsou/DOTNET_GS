-- BLOCO PL/SQL #3 - testes de procedimentos, duas triggers e regras negativas.
DECLARE
    V_ID            NUMBER;
    V_ID_IA         NUMBER;
    V_ID_IA_VALID   NUMBER;
    V_STATUS        VARCHAR2(12);
    V_CICLO         NUMBER;
    V_TOTAL         NUMBER;
    V_ANTES         TIMESTAMP(6);
    V_DEPOIS        TIMESTAMP(6);
BEGIN
    -- 5.1 PROCEDURE 1: comentario simples sem voto / anonimato opcional.
    PKG_COMUNIDADE.PR_REGISTRAR_ATUALIZACAO(
        2, 1, 'COMENTARIO', TO_CLOB('O problema continua perigoso.'), 'S', V_ID
    );
    SELECT COUNT(*) INTO V_TOTAL FROM TB_ATUALIZACAO
     WHERE ID_ATUALIZACAO = V_ID AND ID_USUARIO = 1 AND FL_ANONIMO = 'S';
    IF V_TOTAL <> 1 THEN
        RAISE_APPLICATION_ERROR(-20930,'Procedure nao gravou comentario anonimo.');
    END IF;
    IF PKG_COMUNIDADE.FN_TOTAL_VOTOS_ATIVOS(2,'RESOLVIDO') <> 1 THEN
        RAISE_APPLICATION_ERROR(-20931,'Comentario comum alterou contagem de votos.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('[OK] PR_REGISTRAR_ATUALIZACAO: comentario anonimo sem voto.');

    -- 5.2 NEGATIVO: voto duplicado do mesmo usuario no mesmo ciclo.
    BEGIN
        PKG_COMUNIDADE.PR_REGISTRAR_ATUALIZACAO(
            2, 3, 'RESOLVIDO', TO_CLOB('Tentativa repetida'), 'N', V_ID
        );
        RAISE_APPLICATION_ERROR(-20932,'Duplicidade indevidamente aceita.');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20053 THEN RAISE; END IF;
    END;
    DBMS_OUTPUT.PUT_LINE('[OK] Voto duplicado rejeitado (usuario/ciclo).');

    -- 5.3 NEGATIVO: ADMIN nao pode contribuir, apenas acessar relatorios.
    BEGIN
        PKG_COMUNIDADE.PR_REGISTRAR_ATUALIZACAO(
            1, 5, 'COMENTARIO', TO_CLOB('Admin nao deve escrever'), 'N', V_ID
        );
        RAISE_APPLICATION_ERROR(-20933,'ADMIN indevidamente autorizado.');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20052 THEN RAISE; END IF;
    END;
    DBMS_OUTPUT.PUT_LINE('[OK] ADMIN nao consegue publicar atualizacoes.');

    -- 5.4 FECHAMENTO: a primeira confirmacao ja existe; usuario 3 e o segundo.
    PKG_COMUNIDADE.PR_REGISTRAR_ATUALIZACAO(
        1, 3, 'RESOLVIDO', TO_CLOB('Arvore retirada da passagem.'), 'N', V_ID
    );
    SELECT STATUS, NUM_CICLO INTO V_STATUS, V_CICLO FROM TB_OCORRENCIA
     WHERE ID_OCORRENCIA = 1;
    IF V_STATUS <> 'RESOLVIDA' OR V_CICLO <> 2 THEN
        RAISE_APPLICATION_ERROR(-20934,'Fechamento comunitario falhou.');
    END IF;
    SELECT COUNT(*) INTO V_TOTAL FROM TB_HISTORICO_STATUS
     WHERE ID_OCORRENCIA = 1 AND OPERACAO = 'UPDATE'
       AND STATUS_ANTERIOR = 'ABERTA' AND STATUS_NOVO = 'RESOLVIDA'
       AND CICLO_ANTERIOR = 1 AND CICLO_NOVO = 2 AND ID_USUARIO = 3;
    IF V_TOTAL <> 1 THEN
        RAISE_APPLICATION_ERROR(-20935,'Trigger de auditoria nao registrou fechamento.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('[OK] Segundo voto fecha ocorrencia; trigger auditou old/new.');

    -- 5.5 REABERTURA: dois usuarios diferentes registram PERSISTE no ciclo 2.
    PKG_COMUNIDADE.PR_REGISTRAR_ATUALIZACAO(
        1, 2, 'PERSISTE', TO_CLOB('Ainda ha galhos na via.'), 'S', V_ID
    );
    IF PKG_COMUNIDADE.FN_TOTAL_VOTOS_ATIVOS(1,'PERSISTE') <> 1 THEN
        RAISE_APPLICATION_ERROR(-20936,'Primeiro voto de reabertura nao registrado.');
    END IF;
    PKG_COMUNIDADE.PR_REGISTRAR_ATUALIZACAO(
        1, 3, 'PERSISTE', TO_CLOB('Confirmo o bloqueio na rua.'), 'N', V_ID
    );
    SELECT STATUS, NUM_CICLO INTO V_STATUS, V_CICLO FROM TB_OCORRENCIA
     WHERE ID_OCORRENCIA = 1;
    IF V_STATUS <> 'ABERTA' OR V_CICLO <> 3 THEN
        RAISE_APPLICATION_ERROR(-20937,'Reabertura comunitaria falhou.');
    END IF;
    SELECT COUNT(*) INTO V_TOTAL FROM TB_HISTORICO_STATUS
     WHERE ID_OCORRENCIA = 1 AND OPERACAO = 'UPDATE'
       AND STATUS_ANTERIOR = 'RESOLVIDA' AND STATUS_NOVO = 'ABERTA'
       AND CICLO_ANTERIOR = 2 AND CICLO_NOVO = 3 AND ID_USUARIO = 3;
    IF V_TOTAL <> 1 THEN
        RAISE_APPLICATION_ERROR(-20938,'Trigger nao auditou reabertura.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('[OK] Dois votos reabrem ocorrencia e geram nova auditoria.');

    -- 5.6 NEGATIVO: UPDATE direto do status, sem package, deve ser bloqueado.
    BEGIN
        UPDATE TB_OCORRENCIA SET STATUS = 'RESOLVIDA', NUM_CICLO = 2
         WHERE ID_OCORRENCIA = 4;
        RAISE_APPLICATION_ERROR(-20939,'UPDATE manual de status indevidamente aceito.');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20200 THEN RAISE; END IF;
    END;
    DBMS_OUTPUT.PUT_LINE('[OK] TRG_OCORRENCIA_BIU impediu UPDATE manual de status.');

    -- 5.7 TRIGGER 1: data de alteracao e atualizada ao editar o registro.
    SELECT DT_ATUALIZACAO INTO V_ANTES FROM TB_OCORRENCIA WHERE ID_OCORRENCIA = 2;
    UPDATE TB_OCORRENCIA SET TITULO = TITULO || ' (teste)' WHERE ID_OCORRENCIA = 2;
    SELECT DT_ATUALIZACAO INTO V_DEPOIS FROM TB_OCORRENCIA WHERE ID_OCORRENCIA = 2;
    IF V_DEPOIS < V_ANTES THEN
        RAISE_APPLICATION_ERROR(-20940,'Data de atualizacao retrocedeu.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('[OK] TRG_OCORRENCIA_BIU atualizou timestamp.');

    -- 5.8 PROCEDURE 2 / Java: registrar orientacao SEM_FONTE sem citar dados nao validados.
    PKG_BASE_IA.PR_REGISTRAR_ORIENTACAO(
        2, 4, NULL,
        TO_CLOB('Ainda nao existem fontes verificadas para esse municipio e categoria.'),
        'DEMO-TESTE', 'SEM_FONTE', NULL, 'N', V_ID_IA
    );
    SELECT COUNT(*) INTO V_TOTAL FROM TB_ORIENTACAO_IA
     WHERE ID_ORIENTACAO = V_ID_IA AND ID_USUARIO = 4
       AND ESTADO_ORIENTACAO = 'SEM_FONTE' AND ID_SERVICO IS NULL;
    IF V_TOTAL <> 1 THEN
        RAISE_APPLICATION_ERROR(-20941,'Orientacao sem fonte nao foi registrada.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('[OK] Java pode armazenar estado SEM_FONTE sem inventar contato.');

    -- 5.9 PROCEDURE 2: resposta PARCIAL com fonte revisada; vinculo e atomico.
    PKG_BASE_IA.PR_REGISTRAR_ORIENTACAO(
        1, 4, 3,
        TO_CLOB('Prefeitura de Sao Paulo orienta ligar para 156; horario nao confirmado.'),
        'DEMO-TESTE', 'PARCIAL', 3, 'N', V_ID_IA
    );
    SELECT COUNT(*) INTO V_TOTAL FROM TB_ORIENTACAO_IA I
      JOIN TB_ORIENTACAO_FONTE F ON F.ID_ORIENTACAO = I.ID_ORIENTACAO
     WHERE I.ID_ORIENTACAO = V_ID_IA AND I.ESTADO_ORIENTACAO = 'PARCIAL'
       AND F.ID_FONTE = 3;
    IF V_TOTAL <> 1 THEN
        RAISE_APPLICATION_ERROR(-20942,'Orientacao referenciada nao foi vinculada a fonte.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('[OK] Orientacao com fonte verificada e trecho aprovado.');
    V_ID_IA_VALID := V_ID_IA;

    -- Negativo: servico de Sao Paulo nao atende ocorrencia de Campinas.
    BEGIN
        PKG_BASE_IA.PR_REGISTRAR_ORIENTACAO(
            2, 2, 3, TO_CLOB('Teste de municipio incorreto'),
            'DEMO-TESTE', 'PARCIAL', 3, 'N', V_ID_IA
        );
        RAISE_APPLICATION_ERROR(-20943,'Servico de outro municipio foi aceito.');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20103 THEN RAISE; END IF;
    END;
    DBMS_OUTPUT.PUT_LINE('[OK] Servico incompativel com municipio rejeitado.');

    -- Negativo: dado nao verificado nao pode fundamentar orientacao.
    BEGIN
        PKG_BASE_IA.PR_REGISTRAR_ORIENTACAO(
            1, 2, 3, TO_CLOB('Nao usar fonte falsa'),
            'DEMO-TESTE', 'DISPONIVEL', 1, 'N', V_ID_IA
        );
        RAISE_APPLICATION_ERROR(-20946,'Fonte incorreta foi aceita.');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20104 THEN RAISE; END IF;
    END;
    DBMS_OUTPUT.PUT_LINE('[OK] Fonte ficticia/incompativel rejeitada.');

    -- Trigger de IA: vinculo direto com fonte nao verificada e proibido.
    BEGIN
        INSERT INTO TB_ORIENTACAO_FONTE (ID_ORIENTACAO, ID_FONTE)
        VALUES (V_ID_IA_VALID, 1);
        RAISE_APPLICATION_ERROR(-20947,'Trigger aceitou fonte nao verificada.');
    EXCEPTION WHEN OTHERS THEN
        IF SQLCODE <> -20220 THEN RAISE; END IF;
    END;
    DBMS_OUTPUT.PUT_LINE('[OK] TRG_ORIENTACAO_FONTE_BIU rejeita fonte nao revisada.');

    -- 5.10 TRIGGER 2: nova ocorrencia recebe automaticamente evento INSERT.
    INSERT INTO TB_OCORRENCIA (
        ID_USUARIO, ID_CATEGORIA, ID_MUNICIPIO, TITULO, DESCRICAO,
        LATITUDE, LONGITUDE, FL_ANONIMO
    ) VALUES (
        1, 1, 1, 'Ocorrencia temporaria de teste',
        TO_CLOB('Cadastro para validar a auditoria de criacao.'),
        -23.5505000, -46.6333000, 'S'
    ) RETURNING ID_OCORRENCIA INTO V_ID;
    SELECT COUNT(*) INTO V_TOTAL FROM TB_HISTORICO_STATUS
     WHERE ID_OCORRENCIA = V_ID AND OPERACAO = 'INSERT'
       AND STATUS_ANTERIOR IS NULL AND STATUS_NOVO = 'ABERTA'
       AND CICLO_NOVO = 1 AND ID_USUARIO = 1;
    IF V_TOTAL <> 1 THEN
        RAISE_APPLICATION_ERROR(-20945,'Trigger de criacao nao gravou historico.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('[OK] TRG_OCORRENCIA_AI auditou nova ocorrencia.');

    -- 5.11 Requisicao idempotente: mesma chave/rota/usuario e proibida.
    BEGIN
        INSERT INTO TB_REQUISICAO_IDEMPOTENTE (
            ID_USUARIO, CHAVE, ROTA, METODO_HTTP, HASH_CORPO
        ) VALUES (1,'demo-req-001','/api/v1/ocorrencias','POST',RPAD('f',64,'f'));
        RAISE_APPLICATION_ERROR(-20943,'Chave idempotente repetida foi aceita.');
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL;
    END;
    DBMS_OUTPUT.PUT_LINE('[OK] UNIQUE de idempotencia impede chave repetida.');

    SELECT SUM(TOTAL_OCORRENCIAS) INTO V_TOTAL FROM VW_RELATORIO_OCORRENCIAS;
    IF V_TOTAL <> 6 THEN
        RAISE_APPLICATION_ERROR(-20944,'Relatorio temporario deveria somar 6 ocorrencias.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('[OK] VIEW administrativa agregada = 6 ocorrencias durante o teste.');

    DBMS_OUTPUT.PUT_LINE('[OK] BLOCO 3: procedimentos, triggers, excecoes e regras testadas.');
END;
